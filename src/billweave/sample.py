# ---------------------------------------------------------------- 生成函数

def generate(workspace="."):
    """在 workspace 目录下生成合成样例账单。"""
    workspace = os.path.abspath(workspace)

    def w(path, mode="wb"):
        full = os.path.join(workspace, path)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        return open(full, mode)

    random.seed(42)

    # --- 支付宝 CSV (GBK) ---
    def gen_alipay():
        header = ["交易时间", "交易分类", "交易对方", "对方账号", "商品说明", "收/支",
                  "金额", "收/付款方式", "交易状态", "交易订单号", "商家订单号", "备注"]
        meta = [
            "支付宝交易明细(20260601-20260830)",
            "---------",
            "姓名,测试用户",
            "起始时间,2026-06-01 00:00:00",
            "结束时间,2026-08-30 23:59:59",
            "",
        ]
        with w("bills/支付宝/2026-08-30/支付宝交易明细(20260601-20260830).csv", "wb") as f:
            for line in meta:
                f.write((line + "\n").encode("gb18030"))
            for row in [header] + [list(r) for r in ALIPAY_ROWS]:
                sio = io.StringIO()
                csv.writer(sio).writerow(row)
                f.write(sio.getvalue().encode("gb18030"))

    # --- 微信 XLSX ---
    def gen_wechat():
        from openpyxl import Workbook
        wb = Workbook()
        ws = wb.active
        meta = [
            ["微信支付账单流水文件(20260601-20260830)"],
            ["---------"],
            ["微信昵称:测试用户"],
            ["起始时间:2026-06-01 00:00:00    终点时间:2026-08-30 23:59:59"],
            ["导出类型:交易明细"],
            [],
        ]
        for m in meta:
            ws.append(m)
        ws.append(WX_COLS)
        for r in WX_ROWS:
            ws.append(list(r))
        ws.append(["共8笔记录"])
        with w("bills/微信/2026-08-30/微信支付账单流水文件(20260601-20260830).xlsx") as f:
            wb.save(f)

    # --- 招行流水 PDF ---
    def gen_cmb_pdf():
        try:
            from reportlab.lib.pagesizes import A4
            from reportlab.pdfgen import canvas as pdf_canvas
            from reportlab.pdfbase import pdfmetrics
            from reportlab.pdfbase.cidfonts import UnicodeCIDFont
        except ImportError:
            print("⚠️  跳过 PDF 生成（需要 reportlab）: pip install billweave[sample]",
                  file=sys.stderr)
            return

        path = os.path.join(workspace, "bills", "招商银行", "2026-08-30",
                            "招商银行交易流水(申请时间2026年08月30日10时00分00秒).pdf")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        c = pdf_canvas.Canvas(path, pagesize=A4)
        width, height = A4
        c.setFont("Helvetica", 9)
        c.drawString(60, height - 60, "招商银行交易流水")
        c.drawString(60, height - 76,
                     "户名:测试用户  账号:62************1234  开始日期:20260601  结束日期:20260830")
        xs = [60, 150, 210, 300, 390, 520]
        headers = ["记账日期", "货币", "交易金额", "联机余额", "交易摘要", "对手信息"]
        pdfmetrics.registerFont(UnicodeCIDFont("STSong-Light"))
        y = height - 110
        for x, htxt in zip(xs, headers):
            c.setFont("STSong-Light", 9)
            c.drawString(x, y, htxt)
        for row in CMB_ROWS:
            y -= 16
            for x, val in zip(xs, row):
                c.setFont("STSong-Light", 9)
                c.drawString(x, y, val)
        c.setFont("STSong-Light", 7)
        c.drawString(60, 60, "共9笔交易  重要提示:本流水为合成演示数据,与任何真实账户无关。")
        c.showPage()
        c.save()

    # --- 余额快照（横表） ---
    def gen_balance():
        from openpyxl import Workbook
        wb = Workbook()
        ws = wb.active
        ws.append(["日期", "招商银行", "中国银行", "交通银行", "微信", "支付宝", "余额宝", "其他"])
        ws.append(["2026.08.30", 3179.60, 0, 0, 236.50, 88.00, 1200.00, 0])
        with w("balance/余额快照.xlsx") as f:
            wb.save(f)

    # --- 债务 ---
    def gen_debt():
        with w("debt/债务.csv", "wb") as f:
            f.write("说明:本文件为合成演示数据。".encode("utf-8-sig"))
            f.write(("\n" + ",".join(["对方", "金额", "币种", "日期", "状态", "还款日期"]) + "\n").encode("utf-8"))
            f.write((",".join(["花呗", "450.00", "CNY", "2026-08-30", "未还清", "2026-09-09"]) + "\n").encode("utf-8"))
            f.write((",".join(["借同学小林", "200.00", "CNY", "2026-08-30", "未还清", "2026-09-30"]) + "\n").encode("utf-8"))

    # --- 执行 ---
    gen_alipay()
    gen_wechat()
    gen_cmb_pdf()
    gen_balance()
    gen_debt()
    print(f"✅ 合成样例数据已生成: {workspace}")


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser(description="生成合成样例数据")
    ap.add_argument("--workspace", default=".", help="输出目录（默认当前目录）")
    args = ap.parse_args()
    generate(args.workspace)
